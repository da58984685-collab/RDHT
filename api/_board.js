const SWEAR = /시발|씨발|씨팔|ㅅㅂ|ㅆㅂ|존나|ㅈㄴ|졸라|지랄|병신|ㅂㅅ|새끼|좆|씹|썅|염병|닥쳐|꺼져|미친놈|미친년|또라이/g;
const censor = t => t.replace(SWEAR, m => 'X'.repeat(m.length));

function build(cat, v, st) {
  const S = STYLES[st];
  let t0, body;
  if (S.reg === 't' || S.reg === 'g') { const e = pick(X[S.reg][cat]); t0 = e[0]; body = e[1]; }
  else {
    const tpl = pick(T[cat]), pol = S.reg === 'p';
    t0 = Array.isArray(tpl[0]) ? tpl[0][pol ? 1 : 0] : tpl[0]; body = tpl[pol ? 2 : 1];
  }
  // 첫머리와 마무리는 한 쌍으로 골라 서로 호응하게 합니다 (장소가 있는 글은 절반쯤 장소를 되받음)
  const scary = MON_CATS.includes(cat), soft = SOFT_CATS.includes(cat);
  const ok = x => (scary || x[2] !== 'm') && !(soft && x[2] === 'n');
  const pr = (scary && v.place && chance(0.5)) ? pick(PLACE_PAIRS[S.reg]) : pick(S.pairs.filter(ok));
  let text = (pr[0] + fill(body, v) + pr[1]).trim();
  if (['student', 'curt', 'cynic', 'gsik'].includes(st) && chance(0.35)) text = text.replace(/\.$/, '');   // 가끔 마침표를 빼먹는 실제 글 느낌
  return { title: censor(fill(t0, v)), body: censor(fill(text, v)) };
}
const RANK_W = ['F', 'F', 'E', 'E', 'D', 'D', 'C', 'B', 'A'];

// 이름이 겹치지 않도록, 몬스터 목록을 받아 글감 선택
// ctx: { mons:{F:[..],...}, regions:[long names], sOn:[{name,place}], sKill:[..], sFled:[..], sUsers:[{hn,rank,fame}], fame:[{hn,rank,fame}], magic: 마법소녀 이벤트 중인지 }
function weightedByFame(list) {
  const w = list.map(u => Math.max(1, u.fame || 0)), sum = w.reduce((a, b) => a + b, 0);
  let r = Math.random() * sum;
  for (let i = 0; i < list.length; i++) { r -= w[i]; if (r <= 0) return list[i]; }
  return list[list.length - 1];
}
function pickKind(ctx) {
  if (ctx.magic && Math.random() < 0.25) return 'magic';     // 마법소녀 이벤트 중: 글 4개 중 1개는 '마법헌터' 이야기
  const r = Math.random();
  if (r < 0.30) return 'mon';
  if (r < 0.70) return 'sOn';
  if (r < 0.80) return 'crit';
  if (r < 0.85) return 'praise';
  if (r < 0.90) return 'idle';
  return 'fame';                                      // 나머지 10%: 명성이 높은 헌터가 화제에 오르는 글
}
function makePost(ctx) {
  const a = author();
  let kind = pickKind(ctx), v = {}, tag, cat;
  if (kind === 'sOn') {
    const pool = [];
    ctx.sOn.forEach(x => { for (let i = 0; i < 4; i++) pool.push(['sOn', x]); });
    ctx.sKill.forEach(x => pool.push(['sKill', x]));
    ctx.sFled.forEach(x => pool.push(['sFled', x]));
    if (!pool.length) kind = 'mon';
    else { const [k, x] = pick(pool); v = { mon: x.name, place: x.place }; tag = 'SS급'; cat = k; }
  }
  if (kind === 'mon') {
    const rk = pick(RANK_W);
    v = { rank: rk, mon: pick(ctx.mons[rk]), place: pick(ctx.regions) }; tag = '몬스터'; cat = 'mon';
  } else if (kind === 'magic') {
    tag = '마법헌터';
    if (ctx.fame.length && chance(0.3)) { const u = weightedByFame(ctx.fame); v = { hn: u.hn, rank: u.rank }; cat = 'magicOne'; }
    else cat = 'magic';
  } else if (kind === 'crit') { tag = '사회'; cat = 'crit'; }
  else if (kind === 'idle') { tag = '잡담'; cat = 'idle'; }
  else if (kind === 'fame') {
    if (ctx.fame.length) { const u = weightedByFame(ctx.fame); v = { hn: u.hn, rank: u.rank }; tag = '화제'; cat = 'fame'; }
    else { tag = '잡담'; cat = 'idle'; }
  } else if (kind === 'praise') {
    tag = '칭찬';
    if (ctx.sUsers.length && chance(0.5)) { const u = weightedByFame(ctx.sUsers); v = { hn: u.hn, rank: u.rank }; cat = 'praiseOne'; }
    else cat = 'praiseAll';
  }
  const c = build(cat, v, a.style);
  return { who: a.id, title: c.title, body: c.body, tag };
}
